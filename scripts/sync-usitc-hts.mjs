import { createHash } from 'node:crypto';
import { Buffer } from 'node:buffer';
import { mkdir, readFile, writeFile } from 'node:fs/promises';
import path from 'node:path';
import process from 'node:process';

const currentReleaseUrl = 'https://hts.usitc.gov/reststop/currentRelease';
const sourcePage = 'https://hts.usitc.gov/download';
const sourceExport = 'https://hts.usitc.gov/reststop/exportList?from=0101&to=9999&format=CSV&styles=false';

async function fetchRequired(url) {
  const response = await globalThis.fetch(url, { headers: { 'user-agent': 'PartQuill-HTS-Snapshot/1.0' } });
  if (!response.ok) throw new Error(`${url} returned HTTP ${response.status}`);
  return response;
}

const release = await (await fetchRequired(currentReleaseUrl)).json();
if (!/^\d{4}HTSRev\d+$/.test(release.name ?? '')) {
  throw new Error(`Unexpected USITC release name: ${JSON.stringify(release.name)}`);
}

const csv = Buffer.from(await (await fetchRequired(sourceExport)).arrayBuffer());
const csvText = csv.toString('utf8');
if (csv.length < 3_000_000 || !csvText.includes('8708.30.50.90') || !csvText.includes('Brakes and servo-brakes')) {
  throw new Error('USITC export failed the minimum-size or automotive-heading integrity check.');
}

const match = /^(\d{4})HTSRev(\d+)$/.exec(release.name);
if (!match) throw new Error('Unable to derive a snapshot filename from the USITC release.');
const filename = `hts-${match[1]}-rev${match[2]}.csv`;
const directory = path.resolve('data/tariff');
const sha256 = createHash('sha256').update(csv).digest('hex');
const metadata = {
  release: release.name,
  description: release.description,
  retrievedAt: new Date().toISOString(),
  sourcePage,
  sourceExport,
  filename,
  bytes: csv.length,
  sha256,
  classificationPolicy: 'Description rules return reviewable candidates only. Seller or customs review is required before international publication.'
};

await mkdir(directory, { recursive: true });
try {
  const existingMetadata = JSON.parse(await readFile(path.join(directory, 'metadata.json'), 'utf8'));
  const existingCsv = await readFile(path.join(directory, filename));
  const existingSha256 = createHash('sha256').update(existingCsv).digest('hex');
  if (existingMetadata.release === release.name && existingMetadata.sha256 === sha256 && existingSha256 === sha256) {
    process.stdout.write(`${release.name} is already current (${csv.length} bytes, sha256 ${sha256})\n`);
    process.exit(0);
  }
} catch {
  // A missing or malformed local snapshot is repaired by the validated write below.
}
await writeFile(path.join(directory, filename), csv);
await writeFile(path.join(directory, 'metadata.json'), `${JSON.stringify(metadata, null, 2)}\n`);
await writeFile(
  path.resolve('src/catalog/tariff-release.ts'),
  `// Generated by scripts/sync-usitc-hts.mjs when the official snapshot changes.\nexport const CURRENT_HTS_RELEASE = '${release.name}';\n`
);

process.stdout.write(`Saved ${release.name} (${csv.length} bytes, sha256 ${sha256})\n`);
